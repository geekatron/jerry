        s = mgr.approve_scope(_ENGAGEMENT_ID)
        assert s.current_state == "PROVISIONING"

        s = mgr.activate(_ENGAGEMENT_ID)
        assert s.current_state == "ACTIVE"

        s = mgr.complete_execution(_ENGAGEMENT_ID)
        assert s.current_state == "ANALYZING"

