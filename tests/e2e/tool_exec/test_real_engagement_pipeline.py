        class AutoApprove(OperatorConfirmationPort):
            """Should never be called for E2E-* (pre-approved)."""

            called = False

            def request_approval(self, ctx: GateContext) -> bool:
                AutoApprove.called = True
                return True

            def request_approval_with_timeout(
                self,
                ctx: GateContext,
                timeout_seconds: int,
            ) -> bool | None:
                AutoApprove.called = True
                return True

        eng_dir = tmp_path / "engagements"
        eng_dir.mkdir()
        confirm = AutoApprove()
        mgr = GatedLifecycleManager(
            engagement_dir=eng_dir,
            confirmation_port=confirm,
        )

