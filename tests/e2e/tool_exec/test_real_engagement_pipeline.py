def _wait_for_ssh(ip: str, private_key: Path, *, max_wait: int = 180) -> None:
    """Poll SSH until the droplet accepts connections."""
    for _i in range(max_wait // 5):
        result = subprocess.run(
            [
                "ssh",
                "-o",
                "StrictHostKeyChecking=no",
                "-o",
                "UserKnownHostsFile=/dev/null",
                "-o",
                "ConnectTimeout=5",
                "-o",
                "BatchMode=yes",
                "-i",
                str(private_key),
                f"root@{ip}",
                "echo",
                "ready",
            ],
            capture_output=True,
            text=True,
            timeout=10,
        )
        if result.returncode == 0 and "ready" in result.stdout:
            return
        time.sleep(5)
    pytest.fail(f"SSH not ready on {ip} after {max_wait}s")


