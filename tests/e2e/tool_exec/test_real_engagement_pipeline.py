def _compose_exec(
    compose_file: str,
    service: str,
    cmd: list[str],
    *,
    timeout: int = 60,
) -> tuple[int, str, str]:
    """Execute a command inside a running compose service."""
    result = subprocess.run(
        ["docker", "compose", "-f", compose_file, "exec", "-T", service, *cmd],
        capture_output=True,
        text=True,
        cwd=str(_PROJECT_ROOT),
        timeout=timeout,
    )
    return result.returncode, result.stdout, result.stderr


def _compose_restart(compose_file: str, service: str) -> None:
    """Restart a single compose service."""
    subprocess.run(
        ["docker", "compose", "-f", compose_file, "restart", service],
        capture_output=True,
        cwd=str(_PROJECT_ROOT),
        timeout=60,
    )


def _wait_for_service(compose_file: str, service: str, *, max_wait: int = 45) -> bool:
    """Poll a compose service until healthy or running."""
    for _ in range(max_wait):
        result = subprocess.run(
            ["docker", "compose", "-f", compose_file, "ps", service],
            capture_output=True,
            text=True,
            cwd=str(_PROJECT_ROOT),
            timeout=10,
        )
        output = result.stdout.lower()
        if "healthy" in output or ("up" in output and "exit" not in output):
            return True
        time.sleep(1)
    return False


def _compute_sha256(file_path: Path) -> str:
    """Compute SHA-256 hex digest of a file."""
    sha = hashlib.sha256()
    with file_path.open("rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            sha.update(chunk)
    return sha.hexdigest()


def _get_operator_ip() -> str:
    """Get operator public IP for firewall allowlisting."""
