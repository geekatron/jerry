class TestPhase5EvidenceIntegrity:
    """SHA-256 integrity manifest for all evidence (N3)."""

    def test_build_and_verify_integrity_manifest(
        self,
        project_root: Path,
        engagement_cleanup: list[str],
    ) -> None:
        """Build integrity-manifest.json and verify every hash."""
        eng_dir = project_root / "work" / "engagements" / _ENGAGEMENT_ID
        evidence_dir = eng_dir / "evidence"

        if not evidence_dir.exists():
            # Create engagement + run a tool to generate evidence
            engagement_cleanup.append(_ENGAGEMENT_ID)
            subprocess.run(
                ["uv", "run", "jerry", "tool", "exec", "_", "--init-engagement", _ENGAGEMENT_ID],
                capture_output=True,
                cwd=str(_PROJECT_ROOT),
                timeout=30,
            )
            subprocess.run(
                [
                    "uv",
                    "run",
                    "jerry",
                    "tool",
                    "exec",
                    "--mode",
                    "local",
                    "--engagement-id",
                    _ENGAGEMENT_ID,
                    "syft",
                    "version",
                ],
                capture_output=True,
                cwd=str(_PROJECT_ROOT),
                timeout=60,
            )

        if not evidence_dir.exists():
            pytest.skip("No evidence directory")

        evidence_files = [
            f
            for f in evidence_dir.iterdir()
            if f.is_file()
            and not f.name.endswith(".meta.json")
            and f.name != "integrity-manifest.json"
        ]
        if not evidence_files:
            pytest.skip("No evidence files")

        # Build manifest — CWE-22/FINDING-007: use relative filenames, not absolute paths
        manifest = {}
        for ef in evidence_files:
            manifest[ef.name] = {
                "file": ef.name,
                "sha256": _compute_sha256(ef),
                "size_bytes": ef.stat().st_size,
                "timestamp": datetime.now(tz=UTC).isoformat(),
            }

        manifest_path = evidence_dir / "integrity-manifest.json"
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        assert manifest_path.exists()

        # Verify every hash by recomputation
        loaded = json.loads(manifest_path.read_text(encoding="utf-8"))
        for filename, entry in loaded.items():
            fp = evidence_dir / entry["file"]
            assert fp.exists(), f"Missing: {filename}"
            recomputed = _compute_sha256(fp)
            assert recomputed == entry["sha256"], f"Hash mismatch for {filename}"


